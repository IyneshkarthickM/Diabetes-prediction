-- Create the table for sending notifications to doctors
CREATE TABLE public.doctor_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  patient_name TEXT NOT NULL,
  risk_level TEXT NOT NULL,
  message TEXT,
  is_read BOOLEAN DEFAULT FALSE
);

-- Enable Row Level Security (RLS) on the table
ALTER TABLE public.doctor_notifications ENABLE ROW LEVEL SECURITY;

-- Create a policy that allows any authenticated user to insert a notification
-- and allows any authenticated user to read all notifications.
-- In a real app, you would restrict read access to specific 'doctor' roles.
CREATE POLICY "Enable insert and read for authenticated users"
ON public.doctor_notifications
FOR ALL
USING (auth.role() = 'anon')
WITH CHECK (auth.role() = 'anon');
